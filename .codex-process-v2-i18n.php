foreach (glob(__DIR__ . '/i18n/*.json') as $file) {
	$name = basename($file);
	$data = json_decode(file_get_contents($file), true);
	if (!is_array($data)) {
		fwrite(STDERR, $name . " invalid\n");
		exit(1);
	}

	$copy = in_array($name, ['en-CA.json', 'en-US.json'], true) ? $en : $es;
	foreach ($copy as $key => $value) {
		$data[$key] = $value;
	}

	$encoded = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
	if ($encoded === false) {
		fwrite(STDERR, $name . " encode failed\n");
		exit(1);
	}
	file_put_contents($file, $encoded . "\n");
}

