$localeToLang = [
    'es-MX.json' => 'es',
    'es-CO.json' => 'es',
    'en-CA.json' => 'en',
    'en-US.json' => 'en',
    'fr-CA.json' => 'fr',
    'pt-BR.json' => 'pt',
    'zh-CA.json' => 'zh',
    'zh-CN.json' => 'zh',
    'ko-CA.json' => 'ko',
    'ko-KR.json' => 'ko',
];

foreach ($localeToLang as $file => $lang) {
    $path = __DIR__ . '/i18n/' . $file;
    $json = json_decode((string)file_get_contents($path), true);
    if (!is_array($json)) {
        fwrite(STDERR, $file . " is not valid JSON\n");
        exit(1);
    }

    foreach ($common[$lang] as $key => $value) {
        $json[$key] = $value;
    }

    foreach ($campaigns as $campaignKey => $translations) {
        $copy = $translations[$lang];
        $prefix = 'home.promo.' . $campaignKey;
        $json[$prefix . '.badge'] = $copy['badge'];
        $json[$prefix . '.title'] = $copy['title'];
        $json[$prefix . '.text'] = $copy['text'];
        $json[$prefix . '.offer'] = $copy['offer'];
        for ($i = 1; $i <= 3; $i++) {
            $json[$prefix . '.metric_' . $i . '.value'] = $copy['metric_' . $i . '_value'];
            $json[$prefix . '.metric_' . $i . '.label'] = $copy['metric_' . $i . '_label'];
        }
    }

    file_put_contents(
        $path,
        json_encode($json, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n"
    );
}

echo "home i18n ok\n";
