$localeGroups = [
	'es-MX' => 'es',
	'es-CO' => 'es',
	'en-CA' => 'en',
	'en-US' => 'en',
	'fr-CA' => 'fr',
	'pt-BR' => 'pt',
	'zh-CA' => 'zh',
	'zh-CN' => 'zh',
	'ko-CA' => 'ko',
	'ko-KR' => 'ko',
];

foreach (glob(__DIR__ . '/i18n/*.json') as $file) {
	$locale = basename($file, '.json');
	$group = $localeGroups[$locale] ?? 'es';
	$payload = $translations[$group];
	$raw = file_get_contents($file);
	$decoded = json_decode($raw, true);

	if (!is_array($decoded)) {
		fwrite(STDERR, "Invalid JSON: {$file}\n");
		exit(1);
	}

	$missing = [];
	foreach ($payload as $key => $value) {
		if (!array_key_exists($key, $decoded)) {
			$missing[$key] = $value;
		}
	}

	if (!$missing) {
		continue;
	}

	$insert = '';
	foreach ($missing as $key => $value) {
		$insert .= ",\n\t" . json_encode($key, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)
			. ': '
			. json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
	}

	$pos = strrpos($raw, "\n}");
	if ($pos === false) {
		$pos = strrpos($raw, '}');
	}
	if ($pos === false) {
		fwrite(STDERR, "Could not append to: {$file}\n");
		exit(1);
	}

	file_put_contents($file, substr($raw, 0, $pos) . $insert . substr($raw, $pos));
}
